function Section({ id, n, title, children, lead }: { id: string; n: string; title: string; lead?: ReactNode; children: ReactNode }) {
  return (
    <section id={id} aria-labelledby={`${id}-h`} className="scroll-mt-28 border-t border-line pt-12 pb-4 first:border-t-0 first:pt-0">
      <p className="font-mono text-xs text-signal">{n}</p>
      <h2 id={`${id}-h`} className="display-3 mt-2">
        {title}
      </h2>
      {lead ? <p className="lede mt-3 max-w-2xl !text-[1.02rem]">{lead}</p> : null}
      <div className="mt-8">{children}</div>
    </section>
  );
}

function Sub({ children }: { children: ReactNode }) {
  return <h3 className="mb-3 mt-10 text-[1.05rem] font-semibold text-fg first:mt-0">{children}</h3>;
}

function Bullets({ items }: { items: string[] }) {
  return (
    <ul className="grid gap-2">
      {items.map((item) => (
        <li key={item} className="flex gap-3 text-[0.98rem] leading-relaxed text-fg-2">
          <span className="mt-[0.7em] size-1.5 shrink-0 rounded-full bg-fg-3" aria-hidden="true" />
          {item}
        </li>
      ))}
    </ul>
  );
}

function FeatureList({ label, items, tone }: { label: string; items: Feature[]; tone: "must" | "should" | "could" | "wont" }) {
  if (!items.length) return null;
  const toneClass = {
    must: "border-signal/50 bg-signal-soft text-fg",
    should: "border-line-2 bg-surface-2 text-fg",
    could: "border-line bg-surface text-fg-2",
    wont: "border-line bg-surface text-fg-3",
  }[tone];
  return (
    <div className="mt-8">
      <p className="flex items-center gap-2">
        <span className={`rounded-full border px-2.5 py-1 font-mono text-[0.68rem] uppercase tracking-[0.1em] ${toneClass}`}>{label}</span>
        <span className="font-mono text-xs text-fg-3">{items.length}</span>
      </p>
      <ol className="mt-4 grid gap-3">
        {items.map((f) => (
          <li key={f.title} className="rounded-2xl border border-line bg-surface p-4 sm:p-5">
            <p className={`font-medium ${tone === "wont" ? "text-fg-2 line-through decoration-fg-3/50" : "text-fg"}`}>{f.title}</p>
            <p className="mt-1.5 text-[0.95rem] leading-relaxed text-fg-2">{f.description}</p>
            {f.rationale ? (
              <p className="mt-2.5 border-l-2 border-line-2 pl-3 text-[0.88rem] leading-relaxed text-fg-3">
                <span className="font-mono text-[0.66rem] uppercase tracking-[0.1em]">Why · </span>
                {f.rationale}
              </p>
            ) : null}
          </li>
        ))}
      </ol>
    </div>
  );
}

