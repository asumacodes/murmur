type Params = { slug: string };

export function generateStaticParams() {
  return runs.map((r) => ({ slug: r.slug }));
}

export const dynamicParams = false;

const WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"];
function numberWord(n: number) {
  return WORDS[n] ?? String(n);
}

function shortName(title: string) {
  return title.split(":")[0].trim();
}

export async function generateMetadata({ params }: { params: Promise<Params> }): Promise<Metadata> {
  const { slug } = await params;
  const run = getRun(slug);
  if (!run) return {};
  const name = shortName(run.title);
  const title = `${name} PRD example: ${run.idea}`;
  const description = `A real PRD, competitor research, brand kit, engineering brief, roadmap and ${run.jira.storyCount}-story Jira board for ${name}, generated by Murmur from a ${formatDuration(run.memoSeconds)} voice memo in ${formatDuration(run.runSeconds)}.`;
  return {
    title,
    description,
    alternates: { canonical: `/examples/${slug}` },
    openGraph: { title: `${name}: a real Murmur foundation`, description, url: absoluteUrl(`/examples/${slug}`), type: "article" },
    twitter: { card: "summary_large_image", title: `${name}: a real Murmur foundation`, description },
  };
}

